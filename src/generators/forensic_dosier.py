    @classmethod
    def detect_language(cls, text: str) -> str:
        """
        Detect the language of a document using semantic analysis.
        
        Args:
            text: Document text to analyze
            
        Returns:
            Language code (e.g., 'en', 'es', 'fr')
        """
        if not text or len(text.strip()) < 10:
            return 'en'
        
        try:
            detected = detect(text)
            if detected in cls.SUPPORTED_LANGUAGES:
                return detected
            return 'en'
        except LangDetectException:
            try:
                first_paragraph = text.split('\n\n')[0] if '\n\n' in text else text[:500]
                detected = detect(first_paragraph)
                if detected in cls.SUPPORTED_LANGUAGES:
                    return detected
            except:
                pass
            return 'en'
    
    @classmethod
    def get_disclaimer(cls, language_code: str) -> Dict:
        """Get disclaimer text for a specific language."""
        if language_code in cls.DISCLAIMERS:
            return cls.DISCLAIMERS[language_code]
        return cls.DISCLAIMERS['en']
    
    @classmethod
    def get_language_name(cls, language_code: str) -> str:
        """Get the full language name from code."""
        return cls.SUPPORTED_LANGUAGES.get(language_code, 'English')


